export function visibleErrors(text, startLine = 1, lineAt = index => startLine + lineNumber(text, index) - 1) {
  const prose = maskUrls(text);
  const errors = [];
  for (const [phrase, guidance, regex] of banned) {
    const matches = prose.matchAll(regex);
    for (const match of matches) {
      const line = lineAt(match.index);
      errors.push({
        type: "banned-phrase",
        line,
        phrase,
        guidance
      });
    }
  }

  for (const [regex, id, guidance] of aiTellHard) {
    for (const match of prose.matchAll(regex)) {
      errors.push({ type: `ai-tell:${id}`, line: lineAt(match.index), phrase: match[0].trim(), guidance });
    }
  }

  return errors.concat(punctuationIn(prose, lineAt));
}

export function punctuationErrors(text, startLine = 1) {
  return punctuationIn(maskUrls(text), index => startLine + lineNumber(text, index) - 1);
}

function punctuationIn(prose, lineAt) {
  const errors = [];
  for (const match of prose.matchAll(/[§·—–]/g)) {
    errors.push({
      type: "prose-punctuation", line: lineAt(match.index),
      phrase: match[0], guidance: "문서의 절 번호는 ‘5.3절’로 쓰고, 나열은 조사나 쉼표로 잇는다."
    });
  }
  return errors;
}

function maskUrls(text) {
  return text.replace(/(?:https?:\/\/|mailto:)[^\s<>"')]+/gi, url => " ".repeat(url.length)).trimEnd();
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function lineNumber(value, index) {
  return value.slice(0, index).split(/\r?\n/).length;
}
